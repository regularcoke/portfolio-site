function setBioMode() {
  document.getElementById("bio-text").style.display = "block";
  document.getElementById("name-heading").style.display = "none";
  document.getElementById("nav").classList.remove("nav-gray");

  // Hide lists & deactivate nav
  document.querySelectorAll(".list").forEach(list => list.style.display = "none");
  document.querySelectorAll(".nav h3").forEach(h => h.classList.remove("active"));

  // Clear gallery/caption
  document.getElementById("gallery").innerHTML = "";
  document.getElementById("caption").innerHTML = "";
}

function setNameMode() {
  document.getElementById("bio-text").style.display = "none";
  document.getElementById("name-heading").style.display = "block";
  document.getElementById("nav").classList.add("nav-gray");
}

function preloadAllImages(projects, blogEntries) {
  Object.values(projects).forEach((project) => {
    if (Array.isArray(project.images)) {
      project.images.forEach((src) => {
        const img = new Image();
        img.src = src;
      });
    }
  });

  blogEntries.forEach((entry) => {
    if (Array.isArray(entry.images)) {
      entry.images.forEach((src) => {
        const img = new Image();
        img.src = src;
      });
    }
  });
}

function loadProject(projectKey, clickedLink) {
  const gallery = document.getElementById("gallery");
  const caption = document.getElementById("caption");
  gallery.innerHTML = "";
  caption.innerHTML = "";

  const project = projects[projectKey];
  
  const allLinks = document.querySelectorAll(".list a");
  allLinks.forEach((link) => link.classList.remove("active"));
  if (clickedLink) clickedLink.classList.add("active");

  if (project) {
    project.images.forEach((src, i) => {
      const img = document.createElement("img");
      img.src = src;
      img.alt = project.title || "Project image";
      img.loading = "lazy";
      img.classList.add("lazy");

      // Add click listener to open viewer
      img.addEventListener("click", () => openImageViewer(project.images, i));

      gallery.appendChild(img);
    });

    caption.innerHTML = `
      <h2>${project.title || ""}</h2>
      ${project.year || project.medium ? `<p>${project.year} ${project.medium ? "· " + project.medium : ""}</p>` : ""}
      <p>${project.description || ""}</p>
    `;
  }
}


function toggleSection(clickedHeader) {
  const allHeaders = document.querySelectorAll(".nav h3");
  const allLists = document.querySelectorAll(".list");

  // 🧹 Clear any loaded project
  const gallery = document.getElementById("gallery");
  const caption = document.getElementById("caption");
  gallery.innerHTML = "";
  caption.innerHTML = "";

  setNameMode();

  const targetId = clickedHeader.getAttribute("data-toggle-id");
  const targetList = document.getElementById(targetId);
  const isOpen = targetList.style.display === "block";

  // Close all lists and deactivate headers
  allHeaders.forEach((h) => h.classList.remove("active"));
  allLists.forEach((list) => (list.style.display = "none"));

  // Open clicked one if not already open
  if (!isOpen) {
    targetList.style.display = "block";
    clickedHeader.classList.add("active");

    if (targetId === "worksList") {
      const firstLink = targetList.querySelector("a");
      if (firstLink) {
        firstLink.click();
      }
    }
  }
}

