function toggleSection(clickedHeader) {
  const allHeaders = document.querySelectorAll(".nav h3");
  const allLists = document.querySelectorAll(".list");

  // 🧹 Clear any loaded project
  const gallery = document.getElementById("gallery");
  const caption = document.getElementById("caption");
  gallery.innerHTML = "";
  caption.innerHTML = "";

  setNameMode();

  const targetId = clickedHeader.getAttribute("data-toggle-id");
  const targetList = document.getElementById(targetId);
  const isOpen = targetList.style.display === "block";

  // Close all lists and deactivate headers
  allHeaders.forEach((h) => h.classList.remove("active"));
  allLists.forEach((list) => (list.style.display = "none"));

  // Open clicked one if not already open
  if (!isOpen) {
    targetList.style.display = "block";
    clickedHeader.classList.add("active");

    if (targetId === "worksList") {
      const firstLink = targetList.querySelector("a");
      if (firstLink) {
        firstLink.click();
      }
    }
  }
}

function loadFotos() {
  console.log("loadFotos running, entries:", fotosEntries);

  const camFeed = document.getElementById("camFeed");
  const camNav = document.getElementById("cam");

  if (!camFeed || !camNav) {
    console.error("camFeed or camNav not found");
    return;
  }

  camFeed.innerHTML = "";
  camNav.innerHTML = "";

  fotosEntries.forEach((entry, index) => {
    const entryDiv = document.createElement("div");
    entryDiv.className = "feed-entry";
    entryDiv.id = entry.id || `entry-${index}`;

    const wrapper = document.createElement("div");
    wrapper.className = "image-wrapper";

    wrapper.style.position = "relative";  

    const loader = document.createElement("div");
    loader.className = "loader";
    loader.innerText = "loading...";
    wrapper.appendChild(loader);

    const img = document.createElement("img");
    img.alt = entry.caption || "foto";
    img.loading = "lazy"; 
    img.style.opacity = 0;

    img.style.transition = "opacity 1s ease";  

    const overlay = document.createElement("div");
    overlay.className = "overlay";
    if (entry.id === "bio-photo") {
      overlay.innerHTML = `<div style="color:black;">${entry.caption}</div>`;
    } else {
      overlay.innerHTML = `<div>${entry.caption}</div>`;
    }

    wrapper.appendChild(img);
    wrapper.appendChild(overlay);
    entryDiv.appendChild(wrapper);

    img.onload = () => {
      if (loader && loader.parentNode) loader.remove();  
      img.style.opacity = 1; 
    };

    img.src = entry.src; 
    camFeed.appendChild(entryDiv);

    const dateLink = document.createElement("a");
    dateLink.href = `#entry-${index}`;
    dateLink.textContent = entry.date;
    dateLink.style.display = "block";
    dateLink.onclick = (e) => {
      e.preventDefault();
      document.getElementById(`entry-${index}`).scrollIntoView({ 
        behavior: "smooth", 
        block: "start", 
        inline: "nearest" 
      });
    };
    camNav.appendChild(dateLink);
  });
}


function loadBlog() {
  const gallery = document.getElementById("gallery");
  const caption = document.getElementById("caption");
  const blogList = document.getElementById("blog");
  const blogDates = document.getElementById("blogDates");
  const blogFeed = document.getElementById("blogFeed");
  
  gallery.innerHTML = "";
  caption.innerHTML = "";
  blogDates.innerHTML = "";

  blogEntries.forEach((entry, index) => {
    const link = document.createElement("a");
    link.href = "#entry-" + index;
    link.textContent = entry.date;
    link.style.display = "block"; 
    link.onclick = (e) => {
      e.preventDefault();
      document.getElementById("entry-" + index).scrollIntoView({ behavior: "smooth" });
    };
    blogDates.appendChild(link);


    const post = document.createElement("div");
    post.classList.add("blog-entry");
    post.id = "entry-" + index;
    post.innerHTML = `
      <h2>${entry.title}</h2>
      <p><il>${entry.date}</il></p>
      <p>${entry.content}</p>
      ${
        entry.images && entry.images.length? entry.images.map(src => `<img src="${src}" alt="${entry.title}" loading="lazy" />`).join("")
          : ""
      }
      <p>${entry.content2 || ""}</p>
      ${
        entry.images2 && entry.images2.length? entry.images2.map(src => `<img src="${src}" alt="${entry.title}" loading="lazy" />`).join("")
          : ""
      }
    `;

    blogFeed.appendChild(post);
  });
}


let viewerOverlay, viewerImg, currentIndex, viewerImages;

function openImageViewer(images, index) {
  viewerImages = images;
  currentIndex = index;

  // Create overlay if it doesn't exist
  if (!viewerOverlay) {
    viewerOverlay = document.createElement("div");
    viewerOverlay.id = "image-viewer-overlay";
    viewerOverlay.style.cssText = `
      position: fixed;
      top: 0; left: 0; width: 100%; height: 100%;
      background: white;;
      display: flex;
      align-items: center;
      justify-content: center;
      z-index: 9999;
    `;
    
    // Image element
    viewerImg = document.createElement("img");
    viewerImg.style.cssText = "max-width: 90%; max-height: 90%;";
    viewerOverlay.appendChild(viewerImg);

    // Close on click outside image
    viewerOverlay.addEventListener("click", (e) => {
      if (e.target === viewerOverlay) closeImageViewer();
    });

    // Navigation buttons
    const createButton = (text, action) => {
      const btn = document.createElement("button");
      btn.innerText = text;
      btn.style.cssText = `
        position: absolute; top: 50%; transform: translateY(-50%);
        font-size: small; color: black; background: none; border: none; cursor: pointer;
        user-select: none; padding: 0 1rem;
      `;
      btn.addEventListener("click", action);
      return btn;
    };

    const prevBtn = createButton("back", () => showImage(currentIndex - 1));
    prevBtn.style.left = "10px";
    const nextBtn = createButton("next", () => showImage(currentIndex + 1));
    nextBtn.style.right = "10px";

    viewerOverlay.appendChild(prevBtn);
    viewerOverlay.appendChild(nextBtn);

    document.body.appendChild(viewerOverlay);
  }

  showImage(currentIndex);
  viewerOverlay.style.display = "flex";
}

function showImage(index) {
  if (index < 0) index = viewerImages.length - 1;
  if (index >= viewerImages.length) index = 0;
  currentIndex = index;
  viewerImg.src = viewerImages[currentIndex];
}

function closeImageViewer() {
  if (viewerOverlay) viewerOverlay.style.display = "none";
}

