function loadProject(projectKey, clickedLink) {
  const gallery = document.getElementById("gallery");
  const caption = document.getElementById("caption");
  gallery.innerHTML = "";
  caption.innerHTML = "";

  const project = projects[projectKey];
  
  // Remove active class from all links
  const allLinks = document.querySelectorAll(".list a");
  allLinks.forEach((link) => link.classList.remove("active"));
  if (clickedLink) clickedLink.classList.add("active");

  if (project) {
    // --- Build Gallery ---
    project.images.forEach((src, i) => {
      const img = document.createElement("img");
      img.src = src;
      img.alt = project.title || "Project image";
      img.loading = "lazy";
      img.classList.add("lazy");

      // Add click listener to open viewer
      img.addEventListener("click", () => openImageViewer(project.images, i));

      gallery.appendChild(img);
    });

    // --- Build Caption ---
    caption.innerHTML = `
      <h2>${project.title || ""}</h2>
      ${
        project.year || project.medium
          ? `<p>${project.year} ${project.medium ? "· " + project.medium : ""}</p>`
          : ""
      }
      <p>${project.description || ""}</p>
    `;

    // --- Generate Slug from Title ---
if (project.title) {
  const slug = project.title
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-");

  // Keep clean URL in address bar
  const url = new URL(window.location);
  url.pathname = "/" + slug;
  url.hash = ""; // clear hash
  window.history.pushState({}, "", url);
}
  }
}

function getSlugFromHash() {
  const hash = window.location.hash; // e.g. "#/my-son-is-a-soldier"
  if (!hash.startsWith("#/")) return null;
  return hash.slice(2); // remove "#/"
}

window.addEventListener("DOMContentLoaded", () => {
  const slug = getSlugFromHash();
  if (!slug) return;

  // Find matching project
  const projectKey = Object.keys(projects).find(key => {
    const project = projects[key];
    if (!project.title) return false;

    const projectSlug = project.title
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/[^a-z0-9\s-]/g, "")
      .trim()
      .replace(/\s+/g, "-");

    return projectSlug === slug;
  });

  if (projectKey) {
  const link = document.querySelector(`.list a[href="/${slug}"]`);
  loadProject(projectKey, link);
}
});